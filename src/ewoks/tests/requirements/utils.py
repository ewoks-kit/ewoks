def assert_installed(
    environment: Environment, distributions: List[models.Distribution]
) -> None:
    """Every distribution of `distributions` is installed with its exact version."""
    assert _installed_versions(environment, distributions) == {
        dist.name: dist.version for dist in distributions
    }


def assert_not_installed(
    environment: Environment, distributions: List[models.Distribution]
) -> None:
    """No distribution of `distributions` is installed."""
    assert _installed_versions(environment, distributions) == {
        dist.name: None for dist in distributions
    }


def _installed_versions(
    environment: Environment, distributions: List[models.Distribution]
) -> Dict[str, Optional[str]]:
    return {
        dist.name: environment.distribution_version(dist.name) for dist in distributions
    }


def assert_in_graph_requirements(graph: TaskGraph, *distribution_names) -> None:
    assert distribution_names, "no names provides"
    assert "requirements" in graph.graph.graph, "no requirements"
    requirements = parse_requirements(graph.graph.graph["requirements"])

    existing = {distribution.name for distribution in requirements.distributions}
    not_existing = set(distribution_names) - existing
    assert not not_existing, f"{sorted(not_existing)} not in requirements"


def current_metadata(
    distributions: List[models.Distribution],
    python_version: str,
) -> Dict[str, Any]:
    """Metadata of a python environment with few distributions: the current
    environment can have hundreds, which some package managers take minutes to
    resolve.
    """
    return {
        "system": {
            "system": "",
            "release": "",
            "version": "",
            "machine": "",
            "processor": "",
        },
        "python": {
            "version": python_version,
            "implementation": "",
            "compiler": "",
            "build": "",
        },
        "distributions": distributions,
    }


def manager_requirements(
    manager_name: str,
    files: Optional[Dict[str, str]] = None,
    distributions: Optional[List[models.Distribution]] = None,
    python_version: str = "",
) -> Dict[str, Any]:
    """Workflow requirements as generated by a package manager."""
    return {
        "system": {
            "system": "",
            "release": "",
            "version": "",
            "machine": "",
            "processor": "",
        },
        "python": {
            "version": python_version,
            "implementation": "",
            "compiler": "",
            "build": "",
        },
        "distributions": [dist.model_dump() for dist in distributions or list()],
        "manager": {
            "name": manager_name,
            "version": "",
            "files": files or dict(),
        },
    }
