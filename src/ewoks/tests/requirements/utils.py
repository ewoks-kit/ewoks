def _pinned(name: str, versions: Mapping[Tuple[int, int], str]) -> models.Distribution:
    """Distribution pinned to a version the running python supports. The versions
    are keyed by the lowest python version they support."""
    version = next(
        version
        for python_version, version in sorted(versions.items(), reverse=True)
        if python_version <= sys.version_info[:2]
    )
    return models.Distribution(name=name, version=version)


